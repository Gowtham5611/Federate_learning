"""Suspicious Activity Investigation Report (SAR-Style) Export Module (Phase P).

Generates draft analyst investigation reports for financial crime compliance teams:
- Document Header: "Suspicious Activity Investigation Report — Draft"
- Strict Regulatory Disclaimer: Internal investigative work product; NOT a filed SAR.
- Selectable transactions and account histories with model scores, thresholds, and typology flags.
- Export formats: JSON and standardized Compliance CSV.
- Audit logging of report generation events.
"""

from __future__ import annotations

import io
import json
import logging
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional

logger = logging.getLogger("fedsecureai.compliance_audit")


@dataclass
class InvestigationReportSummary:
    report_id: str
    export_timestamp: str
    analyst_id: str
    document_title: str
    status: str  # "DRAFT_INTERNAL_INVESTIGATION"
    regulatory_disclaimer: str
    model_version: str
    decision_threshold: float
    total_transactions_reviewed: int
    flagged_transactions_count: int
    high_priority_count: int
    total_suspicious_volume_usd: float
    involved_accounts: List[str]
    analyst_narrative_notes: str


@dataclass
class InvestigationReportItem:
    transaction_id: str
    timestamp: str
    from_account: str
    to_account: str
    amount: float
    currency: str
    payment_format: str
    model_risk_score: float
    model_decision: str
    priority_tier: str
    typologies_detected: List[str]
    top_risk_drivers: List[str]
    historical_context_summary: str


class InvestigationReportGenerator:
    """Compiles audit-compliant investigation reports for AML compliance analysts."""

    DISCLAIMER = (
        "IMPORTANT NOTICE: This document is an internal analytical work product generated by "
        "FedSecureAI's risk scoring engine. It is labeled 'Suspicious Activity Investigation Report — Draft' "
        "for internal compliance review only. It does NOT constitute an officially submitted Suspicious Activity "
        "Report (SAR) or Suspicious Transaction Report (STR) to FinCEN, FIU, or any governmental regulatory authority."
    )

    def generate_report(
        self,
        transactions: List[Dict[str, Any]],
        analyst_id: str = "analyst_internal",
        model_version: str = "HI-Small_LSTM_v1.0",
        decision_threshold: float = 0.337784,
        analyst_notes: str = "Internal triage generated based on anomalous sequence risk and typology indicators.",
    ) -> Dict[str, Any]:
        """Compile structured JSON investigation report from evaluated transactions."""
        report_id = f"SAR_DRAFT_{int(datetime.now(timezone.utc).timestamp())}_{analyst_id}"
        export_time = datetime.now(timezone.utc).isoformat()

        accounts_set = set()
        flagged_count = 0
        high_priority_count = 0
        total_vol = 0.0

        items: List[Dict[str, Any]] = []

        for tx in transactions:
            from_acc = str(tx.get("from_account", "N/A"))
            to_acc = str(tx.get("to_account", "N/A"))
            accounts_set.add(from_acc)
            accounts_set.add(to_acc)

            score = float(tx.get("predicted_probability", tx.get("model_risk_score", 0.0)))
            amt = float(tx.get("amount", 0.0))
            is_flagged = score >= decision_threshold

            if is_flagged:
                flagged_count += 1
                total_vol += amt

            tier = str(tx.get("overall_suspicion_tier", "HIGH_PRIORITY_INVESTIGATION" if score >= 0.70 else "MEDIUM_REVIEW" if is_flagged else "LOW_RISK"))
            if tier == "HIGH_PRIORITY_INVESTIGATION":
                high_priority_count += 1

            typos = tx.get("detected_typologies", [])
            typo_names = [t.get("typology_name") if isinstance(t, dict) else str(t) for t in typos]

            drivers = tx.get("top_drivers", ["Anomalous transaction frequency", "High counterparty volume"])

            item = {
                "transaction_id": str(tx.get("transaction_id", tx.get("row_id", "TX_000"))),
                "timestamp": str(tx.get("timestamp", "N/A")),
                "from_account": from_acc,
                "to_account": to_acc,
                "amount": round(amt, 2),
                "currency": str(tx.get("currency", "USD")),
                "payment_format": str(tx.get("payment_format", "ACH")),
                "model_risk_score": round(score, 4),
                "model_decision": "FLAGGED_LAUNDERING" if is_flagged else "CLEARED_LEGITIMATE",
                "priority_tier": tier,
                "typologies_detected": typo_names,
                "top_risk_drivers": drivers,
                "historical_context_summary": f"Target transaction evaluated within 10-step account sliding window.",
            }
            items.append(item)

        summary = {
            "report_id": report_id,
            "export_timestamp": export_time,
            "analyst_id": analyst_id,
            "document_title": "Suspicious Activity Investigation Report — Draft",
            "status": "DRAFT_INTERNAL_INVESTIGATION",
            "regulatory_disclaimer": self.DISCLAIMER,
            "model_version": model_version,
            "decision_threshold": decision_threshold,
            "total_transactions_reviewed": len(transactions),
            "flagged_transactions_count": flagged_count,
            "high_priority_count": high_priority_count,
            "total_suspicious_volume_usd": round(total_vol, 2),
            "involved_accounts_count": len(accounts_set),
            "involved_accounts": sorted(list(accounts_set)),
            "analyst_narrative_notes": analyst_notes,
        }

        # Log audit event
        logger.info(
            "COMPLIANCE_AUDIT: Generated draft investigation report %s by %s for %d transactions (Flagged: %d).",
            report_id,
            analyst_id,
            len(transactions),
            flagged_count,
        )

        return {
            "summary": summary,
            "transactions": items,
        }

    def export_csv_format(self, report_data: Dict[str, Any]) -> str:
        """Serialize investigation items to CSV format for enterprise case management import."""
        headers = [
            "Report_ID",
            "Transaction_ID",
            "Timestamp",
            "From_Account",
            "To_Account",
            "Amount",
            "Currency",
            "Payment_Format",
            "Model_Risk_Score",
            "Decision_Threshold",
            "Model_Decision",
            "Priority_Tier",
            "Typologies_Detected",
            "Regulatory_Status",
        ]

        report_id = report_data.get("summary", {}).get("report_id", "DRAFT")
        th = report_data.get("summary", {}).get("decision_threshold", 0.5)

        rows: List[List[Any]] = []
        for tx in report_data.get("transactions", []):
            rows.append([
                report_id,
                tx.get("transaction_id"),
                tx.get("timestamp"),
                tx.get("from_account"),
                tx.get("to_account"),
                tx.get("amount"),
                tx.get("currency"),
                tx.get("payment_format"),
                tx.get("model_risk_score"),
                th,
                tx.get("model_decision"),
                tx.get("priority_tier"),
                "; ".join(tx.get("typologies_detected", [])),
                "DRAFT_INTERNAL_ONLY",
            ])

        out = io.StringIO()
        out.write("# Suspicious Activity Investigation Report — Draft\n")
        out.write(f"# Disclaimer: {self.DISCLAIMER}\n")
        out.write(",".join(headers) + "\n")
        for r in rows:
            out.write(",".join(f'"{str(c).replace(chr(34), chr(34)+chr(34))}"' for c in r) + "\n")

        return out.getvalue()

